#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

int main() {
	// Включаем поддержку русского языка в консоли
	setlocale(LC_ALL, "Russian");

	// Исходные данные (по образцу задания)
	int n = 3; // делимое
	int L = 333; // делитель
	int k = 3; // количество цифр целой части
	int m = 3; // количество цифр дробной части

	// Вычисление результата
	double result = (double)n / (double)L;

	// Общая ширина числа: 1 знак ('+') + k цифр целой части + 1 точка ('.') + m цифр дробной части

	int total_width = 1 + k + 1 + m;

	// Вывод в точности по требованию задания:
	// 1. Исходные данные в две строки по правому краю
	// 2. Разделитель
	// 3. Результат одной функцией printf с выводом знака (+) и дополнением ведущими нулями
	printf("Дано:\n");
	printf("%8d\n", n);
	printf("%8d\n", L);
	printf("----------------\n");
	printf("Ответ:\n");
	printf("%+0*.*f\n", total_width, m, result);

	return 0;
}