#include <stdio.h>
#include <locale.h>

int main() {
	setlocale(LC_ALL, "Russian");

	// 1) Вывод строки
	printf("123\n"); // подзадание 1

	// 2) Каждая цифра на отдельной строке
	printf("1\n2\n3\n"); // подзадание 2

	// 3) Ступеньками с помощью табуляции
	printf("1\n\t2\n\t\t3\n"); // подзадание 3

	// 4) Ступеньками с разной шириной поля
	printf("%1d\n", 1);
	printf("%2d\n", 2);
	printf("%3d\n", 3);
	printf("%4d\n", 4); // подзадание 4

	// 5) Точность 3 знака
	printf("%10.3f\n", 12.234657); // подзадание 5

	// 6) Точность 5 знаков
	printf("%10.5f\n", 12.234657); // подзадание 6

	// 7) Остаток от деления
	printf("Остаток от деления %d на %d равен %d\n", 5, 2, 5 % 2); // подзадание 7

	// 8-9) Деление и умножение
	printf("7 / 5 = %.2f\n", 7.0 / 5.0); // подзадание 8
	printf("2000 * 4 = %d\n", 2000 * 4); // подзадание 9

	// 10) Исходная строка
	printf("%g разделить %e равно %f\n", 5., 2000000., 5. / 2000000.); // подзадание 10

	// Все спецификаторы на %f:
	printf("%f разделить %f равно %f\n", 5., 2000000., 5. / 2000000.);

	// Все спецификаторы на %g:
	printf("%g разделить %g равно %g\n", 5., 2000000., 5. / 2000000.);

	// Все спецификаторы на %e:
	printf("%e разделить %e равно %e\n", 5., 2000000., 5. / 2000000.);

	// Все спецификаторы на %d (с приведением типов, чтобы программа не вылетала):
	printf("%d разделить %d равно %d\n", (int)5., (int)2000000., (int)(5. / 2000000.));

	return 0;
}